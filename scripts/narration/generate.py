"""
Narration clips for every captioned story beat, spoken by Kokoro (open model,
Apache-2.0, runs locally), written to public/narration/<beat-id>.mp3 with
public/narration/manifest.json.

  python3 -m venv .venv && .venv/bin/pip install kokoro-onnx soundfile
  # model files: kokoro-v1.0.onnx and voices-v1.0.bin from
  # https://github.com/thewh1teagle/kokoro-onnx/releases (model-files-v1.0)
  .venv/bin/python scripts/narration/generate.py --model DIR [--voice af_heart] [--only beat-id ...]

Names: lines that greet the child ({child|little one}) are spoken with the
fallback, since the narrator cannot know every name; the caption still shows it.
Needs ffmpeg on PATH.
"""
import argparse
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

import soundfile as sf
from kokoro_onnx import Kokoro

ROOT = Path(__file__).resolve().parents[2]
STORIES = ['public/story/the-moth.story.json', 'public/story/across-the-sea.story.json']
OUT = ROOT / 'public/narration'


def spoken(beat: dict) -> str | None:
    text = beat.get('text')
    if not text:
        return None
    # {child|fallback} / {performer|fallback} -> fallback.
    text = re.sub(r'\{(child|performer)(?:\|([^}]*))?\}', lambda m: m.group(2) or '', text)
    if beat['type'] == 'journal':
        creature = beat.get('creature', '')
        if creature == '$last':
            return 'Added to your Shadow Journal.'
        text = text.replace('$name', creature.capitalize())
    # Chapter titles read as two short phrases.
    text = text.replace(': ', '. ')
    text = re.sub(r'\s+([,.!?])', r'\1', re.sub(r',\s*,', ',', text)).strip()
    return text or None


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument('--model', required=True, help='folder with kokoro-v1.0.onnx and voices-v1.0.bin')
    ap.add_argument('--voice', default='af_heart')
    ap.add_argument('--speed', type=float, default=0.88)
    ap.add_argument('--only', nargs='*')
    args = ap.parse_args()

    kokoro = Kokoro(str(Path(args.model) / 'kokoro-v1.0.onnx'), str(Path(args.model) / 'voices-v1.0.bin'))
    OUT.mkdir(parents=True, exist_ok=True)
    manifest_path = OUT / 'manifest.json'
    manifest = json.loads(manifest_path.read_text()) if manifest_path.exists() else {}
    clips = manifest.get('clips', {})

    for story in STORIES:
        for beat in json.loads((ROOT / story).read_text())['beats']:
            if args.only and beat['id'] not in args.only:
                continue
            text = spoken(beat)
            if not text:
                continue
            samples, rate = kokoro.create(text, voice=args.voice, speed=args.speed, lang='en-us')
            mp3 = OUT / f"{beat['id']}.mp3"
            with tempfile.NamedTemporaryFile(suffix='.wav') as wav:
                sf.write(wav.name, samples, rate)
                # A short lead-in so the first word is never clipped; mono, speech bitrate.
                subprocess.run(
                    ['ffmpeg', '-y', '-loglevel', 'error', '-i', wav.name, '-af', 'adelay=120,loudnorm=I=-18:TP=-2',
                     '-ac', '1', '-b:a', '56k', str(mp3)],
                    check=True,
                )
            clips[beat['id']] = f"narration/{beat['id']}.mp3"
            print(f"{beat['id']:<24} {text[:70]}", file=sys.stderr)

    manifest = {
        'version': 'shadowplay.narration.v1',
        'note': f'Generated by scripts/narration/generate.py with Kokoro ({args.voice}). Replace with recorded clips any time.',
        'voice': args.voice,
        'clips': dict(sorted(clips.items())),
    }
    manifest_path.write_text(json.dumps(manifest, indent=2) + '\n')


if __name__ == '__main__':
    main()
